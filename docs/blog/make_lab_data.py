"""Build lab-data.js for the interactive figures in the ntlaks.dev post, from this project's run records.

  .venv/Scripts/python docs/blog/make_lab_data.py <ntlaks-writing>/public/labs/teaching-whisper-isixhosa/lab-data.js
Inputs: release/video/src/data.json (FLEURS clips with real model outputs), runs/R-0012/model/log_history.json
(training curves), data/models/R-0012/model.safetensors (one real weight), and numbers from results.md.
"""
import json
import sys

import numpy as np
from safetensors.numpy import safe_open

v = json.load(open("release/video/src/data.json", encoding="utf-8"))


def sub(b, n=64):
    a = np.array(b)
    k = len(a) / n
    return [round(float(a[int(i * k):max(int(i * k) + 1, int((i + 1) * k))].max()), 3) for i in range(n)]


clips = {}
for name in ("loop", "train"):
    c = v["clips"][name]
    clips[name] = {"src": f"audio/{name}.m4a", "seconds": c["seconds"], "start": c["speech_start"], "end": c["speech_end"],
                   "bars": sub(c["bars"]), "said": c["said"], "stock": c["stock"], "stockName": c["stock_name"],
                   "ours": c["r0012"], "fleurs": c["fleurs_id"]}
h = json.load(open("runs/R-0012/model/log_history.json"))
loss = [[e["step"], round(e["loss"], 4)] for e in h if "loss" in e]
nchlt = [[e["step"], e["eval_nchlt_cer"]] for e in h if "eval_nchlt_cer" in e]
fleurs = [[e["step"], e["eval_fleurs_cer"]] for e in h if "eval_fleurs_cer" in e]

name = "model.decoder.layers.0.self_attn.q_proj.weight"
row = safe_open("data/models/R-0012/model.safetensors", "np").get_tensor(name)[0].astype("float32")
w = float(row[7])


def q(bits):
    m = 2 ** (bits - 1) - 1
    s = float(np.abs(row).max()) / m
    return round(int(round(w / s)) * s, 9), int(round(w / s))


# "The sentence that learned": one FLEURS test sentence through every stage, with each stage's real output
import glob
import os
import sys as _sys
_sys.path.insert(0, "src")
import jiwer  # noqa: E402
from scoring import normalise  # noqa: E402


def preds(path):
    return {o["id"]: o for o in map(json.loads, open(glob.glob(path, recursive=True)[0], encoding="utf-8"))}


SID = "fleurs_17388926234373433928"
stages = [  # (title, run whose output is shown, FLEURS test CER of that model (results.md), spent so far in $ (results.md), model)
    ("Out of the box", "runs/R-0006/**/predictions.jsonl", "R-0006", 65.45, 0.13, "whisper-small, 244 million numbers"),
    ("First lesson: 51 hours of NCHLT", "runs/R-0005/**/predictions.jsonl", "R-0005", 29.81, 2.28, "whisper-small, taught on NCHLT"),
    ("More varied data: + FLEURS", "runs/R-0007/eval_fleurs/predictions.jsonl", "R-0007", 10.16, 4.25, "whisper-small, NCHLT + FLEURS"),
    ("A bigger model", "runs/R-0012/eval_fleurs/predictions.jsonl", "R-0012", 8.03, 9.59, "whisper-medium, 769 million numbers"),
]
ref = None
story = []
for title, path, run, cer_test, spent, model in stages:
    o = preds(path)[SID]
    ref = normalise(o["text"])
    hyp = normalise(o["hyp"])
    story.append({"title": title, "run": run, "hyp": hyp, "cerSentence": round(100 * jiwer.cer(ref, hyp), 1),
                  "cerTest": cer_test, "spent": spent, "model": model})

data = {"clips": clips, "curves": {"loss": loss, "nchlt": nchlt, "fleurs": fleurs},
        "story": {"ref": ref, "fleurs": SID, "stages": story},
        "leak": [{"key": "all", "label": "NCHLT test", "cer": 2.98, "run": "R-0004",
                  "why": "2 770 clips from 8 speakers the model never heard. But 82% of these clips repeat a sentence that was also in the training data, so the model partly remembered the answers."},
                 {"key": "unseen", "label": "NCHLT, new sentences only", "cer": 6.2, "run": "R-0004",
                  "why": "The same test with every repeated sentence removed. Same speakers, same style, but sentences the model had never read. The error more than doubles."},
                 {"key": "fleurs", "label": "FLEURS, new and longer", "cer": 29.81, "run": "R-0005",
                  "why": "Google's FLEURS: longer sentences in a different style, none of them in training. The model also glued words together here, writing 5 910 words where there should have been 16 703."}],
        "weight": {"tensor": name + "[0][7]", "fp32": float(np.float32(w)), "fp16": float(np.float16(w)),
                   "int8": q(8)[0], "int8_code": q(8)[1], "int4": q(4)[0], "int4_code": q(4)[1]},
        "sizes": {"32": 3.06, "16": 1.53, "8": 0.775, "4": 0.39}}
with open(sys.argv[1], "w", encoding="utf-8") as f:
    f.write("// Real values from the isiXhosa Speech AI run records (R-0004, R-0005, R-0006, R-0011, R-0012, R-0013).\n"
            "// Generated by the project; edit the project, not this file.\nexport const DATA = " + json.dumps(data, ensure_ascii=False) + ";\n")
print("wrote", sys.argv[1])
